PLACEHOLDERS = {
    "migAppsCount": {"count": {"type": "int"}},
    "migScanResultLibrary": {"count": {"type": "int"}},
    "migScanResultDownloads": {"count": {"type": "int"}},
    "migImportLibraryDone": {"count": {"type": "int"}},
    "migImportDownloadsDone": {"count": {"type": "int"}},
}


def inject(path: str, data: dict) -> None:
    with open(path, encoding="utf-8") as f:
        existing = json.load(f, object_pairs_hook=collections.OrderedDict)
    added = 0
    for key, value in data.items():
        if key in existing:
            continue
        existing[key] = value
        if key in PLACEHOLDERS:
            existing["@" + key] = {"placeholders": PLACEHOLDERS[key]}
        added += 1
    with open(path, "w", encoding="utf-8") as f:
        json.dump(existing, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"{path}: +{added}")


