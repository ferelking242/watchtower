  static final Map<String, GalleryComponentDescriptor> _byId = {
    for (final descriptor in descriptors) ...{
      descriptor.id: descriptor,
      for (final alias in descriptor.aliases) alias: descriptor,
    },
  };

  static GalleryComponentDescriptor? resolve(String id) => _byId[id];

  static bool supports(String id) => _byId.containsKey(id);

  static List<GalleryComponentDescriptor> forContext({bool selectableOnly = false}) =>
      List.unmodifiable(
        descriptors.where(
          (descriptor) => !selectableOnly || descriptor.selectable,
        ),
      );

  static List<String> get availableIds => _byId.keys.toList(growable: false);

  /// Descriptors grouped by category, preserving the catalog declaration order.
  static Map<String, List<GalleryComponentDescriptor>> byCategory({
    bool selectableOnly = false,
  }) {
    final grouped = <String, List<GalleryComponentDescriptor>>{};
    for (final descriptor in descriptors) {
      if (selectableOnly && !descriptor.selectable) continue;
      grouped.putIfAbsent(descriptor.category, () => []).add(descriptor);
    }
    return grouped;
  }
