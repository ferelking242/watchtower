// lib/models/gallery_component_catalog.dart
//
// Single source of truth for every component shown in the developer gallery.
//
// The gallery (`lib/modules/dev/component_gallery_screen.dart`) documents the
// whole reusable card library, but only a handful of those cards were wired to
// the layout interpreter, so `MangaHomeScreen` and `WatchExtensionHomeScreen`
// could not render them. This catalog gives every public, reusable gallery
// component a stable JSON id, a renderer family and a loading preview, so the
// declarative layout JSON can select any of them.
//
// The ids are stored in `GalleryComponentDescriptor.id` and are always written
// to layout JSON in kebab-case (for example `movie-details`). The matching
// widgets live in `lib/modules/watch/home/gallery_component_renderer.dart`.

import 'package:watchtower/models/layout_component_registry.dart';

/// Renderer families implemented for gallery components.
///
/// Each family maps a set of JSON component ids to an adapter that builds the
/// real card from extension-home content. Unlike
/// [LayoutComponentRenderer] (which keeps the legacy extension rails compact),
/// this enum exposes the full gallery card library.
enum GalleryComponentFamily {
  richMedia,
  streaming,
  collections,
  episodes,
  ranking,
  mangaChapter,
  mangaVolume,
  mangaGenre,
  mangaReader,
  mangaUniverse,
  mangaStats,
  homeHero,
  // Reuse the existing extension renderers for the shared rails.
  posterRail,
  spotlight,
  banner,
  ranked,
  landscape,
  grid,
  swipe,
}

/// The JSON-facing definition of one gallery component.
class GalleryComponentDescriptor {
  const GalleryComponentDescriptor({
    required this.id,
    required this.className,
    required this.label,
    required this.category,
    required this.description,
    required this.renderer,
    required this.loadingPreview,
    this.aliases = const [],
    this.selectable = true,
  });

  /// Stable identifier written to layout JSON (kebab-case).
  final String id;

  /// Main Dart class the gallery previews for this component.
  final String className;
  final String label;
  final String category;
  final String description;
  final GalleryComponentFamily renderer;
  final LayoutComponentLoadingPreview loadingPreview;
  final List<String> aliases;

  /// Compatibility-only descriptors stay valid in existing JSON but are not
  /// suggested as new choices.
  final bool selectable;
}

